<?php
// Capture anything the includes below might print by accident (a stray
// blank line before "<?php", a PHP notice, a BOM...). Even one extra byte
// in front of image data makes the browser show a broken image, so we
// throw that output away just before sending the photo.
ob_start();

require __DIR__ . '/../config/db.php';
require __DIR__ . '/../includes/auth.php';
require __DIR__ . '/../includes/functions.php';
require_role('admin');

$instituteId = current_institute_id();
$studentId = (int)($_GET['id'] ?? 0);
$slot = $_GET['slot'] ?? 'main';
$debug = isset($_GET['debug']);

/** Plain-text error response (never HTML, never mixed into image bytes). */
function photo_fail(int $code, string $message): void
{
    while (ob_get_level() > 0) { ob_end_clean(); }
    http_response_code($code);
    header('Content-Type: text/plain; charset=utf-8');
    echo $message;
    exit;
}

/** Works out the real image type of a file. Tries fileinfo first, then
 *  getimagesize(), then the file extension (which upload code derived from
 *  the validated content), so a server without the fileinfo extension
 *  can't break photo display. Returns null if it isn't an image. */
function photo_detect_mime(string $path): ?string
{
    $allowed = ['image/jpeg', 'image/png', 'image/gif', 'image/webp'];
    $mime = null;

    if (function_exists('finfo_open')) {
        $finfo = @finfo_open(FILEINFO_MIME_TYPE);
        if ($finfo) {
            $found = @finfo_file($finfo, $path);
            finfo_close($finfo);
            if (is_string($found)) $mime = $found;
        }
    }
    if (!in_array($mime, $allowed, true) && function_exists('getimagesize')) {
        $info = @getimagesize($path);
        if ($info && !empty($info['mime'])) $mime = $info['mime'];
    }
    if (!in_array($mime, $allowed, true)) {
        $byExt = ['jpg' => 'image/jpeg', 'jpeg' => 'image/jpeg', 'png' => 'image/png', 'gif' => 'image/gif', 'webp' => 'image/webp'];
        $mime = $byExt[strtolower(pathinfo($path, PATHINFO_EXTENSION))] ?? null;
    }
    return in_array($mime, $allowed, true) ? $mime : null;
}

if (!isset(STUDENT_PHOTO_SLOTS[$slot]) || !$studentId || !student_belongs_to_institute($conn, $studentId, $instituteId)) {
    photo_fail(404, 'Not found.');
}

$cols = STUDENT_PHOTO_SLOTS[$slot];
$stmt = $conn->prepare("SELECT {$cols['stored']} AS stored, {$cols['original']} AS original FROM students WHERE id = ?");
$stmt->bind_param('i', $studentId);
$stmt->execute();
$row = $stmt->get_result()->fetch_assoc();
$stmt->close();

$stored = $row['stored'] ?? null;
// Stored names are random hex + extension generated by the app; basename()
// is a belt-and-braces guard so a tampered DB value can never escape the folder.
$filePath = $stored ? __DIR__ . '/../uploads/student_photos/' . basename($stored) : null;

// Everything below only reads the file — release the session lock now so
// the page's other requests (and the 2 extra photos) aren't queued behind this one.
session_write_close();

/* ---- ?debug=1 : one-click diagnosis, for admins only (role checked above) ---- */
if ($debug) {
    $info = [
        'student_id'            => $studentId,
        'slot'                  => $slot,
        'db_stored_filename'    => $stored,
        'db_original_filename'  => $row['original'] ?? null,
        'resolved_path'         => $filePath ? (realpath($filePath) ?: $filePath) : null,
        'file_exists'           => $filePath ? is_file($filePath) : false,
        'file_readable'         => $filePath ? is_readable($filePath) : false,
        'file_size_bytes'       => ($filePath && is_file($filePath)) ? filesize($filePath) : null,
        'detected_mime'         => ($filePath && is_file($filePath)) ? photo_detect_mime($filePath) : null,
        'fileinfo_extension'    => function_exists('finfo_open'),
        'php_version'           => PHP_VERSION,
        'server_software'       => $_SERVER['SERVER_SOFTWARE'] ?? null,
        'zlib_output_compression' => ini_get('zlib.output_compression'),
        'stray_output_discarded_bytes' => ob_get_level() > 0 ? strlen((string)ob_get_contents()) : 0,
        'photos_folder_exists'  => is_dir(__DIR__ . '/../uploads/student_photos/'),
        'photos_folder_readable' => is_readable(__DIR__ . '/../uploads/student_photos/'),
        'photos_folder_writable' => is_writable(__DIR__ . '/../uploads/student_photos/'),
    ];
    while (ob_get_level() > 0) { ob_end_clean(); }
    header('Content-Type: text/plain; charset=utf-8');
    echo json_encode($info, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    exit;
}

if (!$stored) {
    photo_fail(404, 'No photo uploaded for this slot.');
}
if (!is_file($filePath) || !is_readable($filePath)) {
    photo_fail(404, 'File is missing from storage (or not readable by the web server).');
}
$mime = photo_detect_mime($filePath);
if ($mime === null) {
    photo_fail(415, 'Stored file is not a valid image.');
}

$size = filesize($filePath);
$mtime = filemtime($filePath);
$etag = '"' . md5($stored . '|' . $size . '|' . $mtime) . '"';

// Throw away anything printed so far (see top of file) before sending bytes.
while (ob_get_level() > 0) { ob_end_clean(); }
// Compression + a fixed Content-Length is a classic cause of truncated images.
@ini_set('zlib.output_compression', '0');
if (function_exists('apache_setenv')) { @apache_setenv('no-gzip', '1'); }

// The session layer adds "never cache" headers; photos are private but
// safe to revalidate cheaply, so replace them (avoids re-downloading
// multi-MB photos on every page view).
header_remove('Pragma');
header_remove('Expires');
header('Cache-Control: private, no-cache');
header('ETag: ' . $etag);
header('Last-Modified: ' . gmdate('D, d M Y H:i:s', $mtime) . ' GMT');
header('X-Content-Type-Options: nosniff');

if (($_SERVER['HTTP_IF_NONE_MATCH'] ?? '') === $etag) {
    http_response_code(304);
    exit;
}

// ASCII fallback name + RFC 5987 UTF-8 name, so Kurdish/Arabic original
// filenames can never produce an invalid header.
$original = (string)($row['original'] ?: $stored);
$asciiName = preg_replace('/[^A-Za-z0-9._-]+/', '_', $original);
if ($asciiName === '' || $asciiName === '_' || !preg_match('/[A-Za-z0-9]/', $asciiName)) {
    $asciiName = $stored;
}

header('Content-Type: ' . $mime);
header('Content-Disposition: inline; filename="' . $asciiName . '"; filename*=UTF-8\'\'' . rawurlencode($original));
header('Content-Length: ' . $size);
readfile($filePath);
exit;
